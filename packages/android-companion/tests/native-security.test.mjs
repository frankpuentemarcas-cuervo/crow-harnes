test('Pangolin QR auth is origin-bound, confirmed on Android, encrypted at rest and never returned in the public profile', () => {
  const native = source('CrowGatewayPlugin'), auth = source('PangolinAuth'), policy = source('EndpointPolicy'), ui = readFileSync(new URL('../src/main.tsx', import.meta.url), 'utf8')
  assert.match(native, /PangolinAuth\.validate\(endpoint, proxyAuth\)/)
  assert.match(native, /destinationConfirmed/); assert.match(ui, /El dominio coincide exactamente con Windows/)
  assert.match(policy, /relayRoute\|proxyAuth/)
  assert.match(native, /finally \{ if \(proxyAuth != null\) \{ proxyAuth\.remove\("token"\); proxyAuth\.remove\("tokenId"\); proxyAuth\.remove\("origin"\)/)
  assert.match(native, /PangolinAuth\.headers\(request, endpoint, proxyAuth\)/)
  assert.match(native, /PangolinAuth\.headers\(requestBuilder, endpoint, record\.optJSONObject\("proxyAuth"\)\)/)
  assert.match(auth, /target\.host\(\)\.equals\(allowed\.host\(\)\)/); assert.match(auth, /target\.port\(\) != allowed\.port\(\)/); assert.match(auth, /!target\.isHttps\(\)/)
  assert.match(auth, /value\.charAt\(i\) < 33 \|\| value\.charAt\(i\) > 126/)
  assert.match(native, /saved\.put\("proxyAuth", proxyAuth\)[\s\S]*store\.save\(id, saved\)/)
  const profile = native.slice(native.indexOf('JSONObject profile ='), native.indexOf('@PluginMethod public void listProfiles'))
  assert.doesNotMatch(profile, /profile\.put\("(?:proxyAuth|token|tokenId)"/)
  assert.doesNotMatch(native, /catch \(Exception invalid\) \{ forget\(id\)/)
  assert.match(native, /PangolinAuth\.rejected\(response\.code\(\), response\.header\("X-Crow-Mobile-API"\)\)/)
  assert.match(auth, /status == 403 && !"1"\.equals\(crowMarker\)/)
  assert.doesNotMatch(native + auth + ui, /Log\.|System\.out|console\.(?:log|debug|info)\(/)
  assert.equal(existsSync(new URL('../android/app/src/main/java/dev/crow/companion/PangolinPrompt.java', import.meta.url)), false)
})

test('native gateway translates only bounded known Crow error codes without changing auth or retry behavior', () => {
  const native = source('CrowGatewayPlugin'), errors = source('MobileErrorMessages')
  assert.equal((native.match(/MobileErrorMessages\.fromResponse\(response\.code\(\), response\.body\(\), response\.header\("X-Crow-Mobile-API"\)\)/g) || []).length, 2)
  assert.match(native, /response\.code\(\) == 401[\s\S]*accessCredentials\.remove\(profileId\)/)
  assert.match(native, /PangolinAuth\.rejected\(response\.code\(\), response\.header\("X-Crow-Mobile-API"\)\)/)
  assert.match(native, /if \(response\.code\(\) == 401 \|\| \(proxyAuth != null && PangolinAuth\.rejected[\s\S]*?\}\s*if \(response\.isRedirect\(\)\)[\s\S]*?if \(!response\.isSuccessful\(\)\) throw new IllegalStateException\(MobileErrorMessages\.fromResponse/)
  assert.match(errors, /fromResponse\(int status, ResponseBody body, String crowMarker\)/)
  assert.match(errors, /if \(!"1"\.equals\(crowMarker\)\) return fallback/)
  assert.match(errors, /MAX_ERROR_BODY_BYTES\s*=\s*8192/)
  for (const code of ['INVALID_ORIGIN', 'GATEWAY_UNAVAILABLE', 'HOST_UNAVAILABLE', 'DEVICE_REJECTED', 'GRANT_REQUIRED', 'RATE_LIMITED', 'NOT_FOUND', 'INVALID_REQUEST', 'REQUEST_CONFLICT']) assert.match(errors, new RegExp(`case "${code}"`))
  assert.match(errors, /Crow rechazó la acción \(HTTP /)
  assert.match(errors, /if \(body == null\) return fallback/)
  assert.match(errors, /if \(!\(codeValue instanceof String\)\) return fallback/)
  assert.match(errors, /default: return "Crow rechazó la acción/)
  assert.doesNotMatch(errors, /optString\("error"|getString\("error"/)
  assert.match(errors, /Verificá el estado antes de repetirla/)
  assert.match(native, /retryOnConnectionFailure\(false\)/)
})
